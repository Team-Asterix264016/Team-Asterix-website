/** The member of `teamNo` with this roll number, or null. */
export function findTeamMember(teamNo, rollNo) {
    const members = EXPO_TEAMS.get(Number(teamNo));
    if (!members) return null;
    const wanted = String(rollNo || '').replace(/\s+/g, '');
    return members.find((m) => m.rollNo === wanted) || null;
}
