/** teamNo -> [{ name, rollNo }] */
export const EXPO_TEAMS = new Map();
for (const line of TEAM_ROWS.trim().split('\n')) {
    const [team, name, rollNo] = line.split('|').map((part) => part.trim());
    const teamNo = Number(team);
    if (!EXPO_TEAMS.has(teamNo)) EXPO_TEAMS.set(teamNo, []);
    EXPO_TEAMS.get(teamNo).push({ name, rollNo });
}

export const EXPO_TEAM_COUNT = EXPO_TEAMS.size;

